// Needs pg-src, mysql-src and mssql from dev/docker-compose.yml:
//
//	podman compose -f dev/docker-compose.yml up -d pg-src mysql-src mssql
//	go test -tags integration ./internal/schema/...

var testDBSeq atomic.Int64

type server struct {
	driver string
	dsn    func(database string) string
	admin  string
	create func(name string) string
	drop   func(name string) string
}

var (
	pgServer = server{
		driver: "pgx",
		dsn: func(db string) string {
			u := url.URL{Scheme: "postgres", User: url.UserPassword("postgres", "postgres"),
				Host: "127.0.0.1:5432", Path: "/" + db, RawQuery: "sslmode=disable"}
			return u.String()
		},
		admin:  "postgres",
		create: func(n string) string { return "CREATE DATABASE " + n },
		drop:   func(n string) string { return "DROP DATABASE " + n + " WITH (FORCE)" },
	}
	mysqlServer = server{
		driver: "mysql",
		dsn: func(db string) string {
			c := mysql.NewConfig()
			c.User, c.Passwd = "root", "root"
			c.Net, c.Addr = "tcp", "127.0.0.1:3306"
			c.DBName = db
			return c.FormatDSN()
		},
		create: func(n string) string { return "CREATE DATABASE " + n },
		drop:   func(n string) string { return "DROP DATABASE " + n },
	}
	mssqlServer = server{
		driver: "sqlserver",
		dsn: func(db string) string {
			q := url.Values{}
			q.Set("database", db)
			q.Set("TrustServerCertificate", "true")
			u := url.URL{Scheme: "sqlserver", User: url.UserPassword("sa", "Passw0rd!"),
				Host: "127.0.0.1:1433", RawQuery: q.Encode()}
			return u.String()
		},
		admin:  "master",
		create: func(n string) string { return "CREATE DATABASE " + n },
		drop: func(n string) string {
			return "ALTER DATABASE " + n + " SET SINGLE_USER WITH ROLLBACK IMMEDIATE; DROP DATABASE " + n
		},
	}
)

// open creates a throwaway database, applies ddl, and drops it on cleanup.
func (s server) open(t *testing.T, ddl ...string) *sql.DB {
	t.Helper()
	ctx, cancel := context.WithTimeout(context.Background(), 60*time.Second)
	defer cancel()

	admin, err := sql.Open(s.driver, s.dsn(s.admin))
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { admin.Close() })
	if err := admin.PingContext(ctx); err != nil {
		t.Fatalf("ping %s: %v (is dev/docker-compose.yml up?)", s.driver, err)
	}
	name := fmt.Sprintf("schema_it_%d_%d", time.Now().UnixNano(), testDBSeq.Add(1))
	if _, err := admin.ExecContext(ctx, s.create(name)); err != nil {
		t.Fatal(err)
	}

	db, err := sql.Open(s.driver, s.dsn(name))
	if err != nil {
		t.Fatal(err)
	}
	// Registered after admin's cleanup, so it runs first: close before drop.
	t.Cleanup(func() {
		db.Close()
		if _, err := admin.Exec(s.drop(name)); err != nil {
			t.Errorf("drop %s: %v", name, err)
		}
	})
	for _, stmt := range ddl {
		if _, err := db.ExecContext(ctx, stmt); err != nil {
			t.Fatalf("%s: %v", stmt, err)
		}
	}
	return db
}

func countRows(t *testing.T, db *sql.DB, table string) int {
	t.Helper()
	var n int
	if err := db.QueryRow("SELECT COUNT(*) FROM " + table).Scan(&n); err != nil {
		t.Fatal(err)
	}
	return n
}

func TestPGRoundTrip(t *testing.T) {
	src := pgServer.open(t,
		`CREATE TABLE users (
			id         int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			email      varchar(255) NOT NULL,
			nick       varchar(50) DEFAULT 'guest',
			score      numeric(10,2) NOT NULL DEFAULT 0,
			created_at timestamptz DEFAULT now(),
			CONSTRAINT users_email_key UNIQUE (email)
		)`,
		`CREATE INDEX ix_nick ON users (nick)`,
		`CREATE TABLE orders (id serial PRIMARY KEY, user_id int, total numeric(10,2))`,
		`CREATE INDEX ix_orders_user ON orders (user_id)`,
		`CREATE TABLE tags (post int NOT NULL, tag text NOT NULL, PRIMARY KEY (post, tag))`,
		`CREATE SCHEMA sales`,
		`CREATE TABLE sales."Region" ("Code" char(2) PRIMARY KEY)`,
	)
	dst := pgServer.open(t,
		`CREATE TABLE users (id int PRIMARY KEY, email varchar(100), legacy text, score int)`,
		`CREATE INDEX ix_nick ON users (email)`,
		`CREATE INDEX ix_legacy ON users (legacy)`,
		`INSERT INTO users (id, email, score) VALUES (1, 'a@x', 5)`,
		`CREATE TABLE tags (post int NOT NULL, tag text NOT NULL, PRIMARY KEY (post))`,
		`CREATE TABLE audit (id int)`,
		`CREATE SCHEMA sales`,
	)
	roundTrip(t, dialect.PostgreSQL{}, src, dst)
	if n := countRows(t, dst, "users"); n != 1 {
		t.Errorf("users rows = %d, want 1", n)
	}
}

