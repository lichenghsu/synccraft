package schema

import (
	"fmt"
	"regexp"
	"strings"

	"github.com/lichenghsu/synccraft/internal/dialect"
)

type postgresDDL struct{ d dialect.PostgreSQL }

var (
	pgNextval = regexp.MustCompile(`^nextval\('.*'::regclass\)$`)
	pgSerial  = map[string]string{"integer": "serial", "bigint": "bigserial", "smallint": "smallserial"}
)

func (g postgresDDL) statements(cur *Table, c Change) ([]string, error) {
	d := g.d
	t := qualified(d, c.Table)
	col := func(x *dialect.Column) string { return d.QuoteIdent(x.Name) }

	switch c.Kind {
	case AddTable:
		return createTable(d, t, c.Create, g.columnDef, g.createIndex(c.Table))
	case DropTable:
		return []string{"DROP TABLE " + t}, nil
	case AddColumn:
		return []string{"ALTER TABLE " + t + " ADD COLUMN " + g.columnDef(*c.Column)}, nil
	case DropColumn:
		return []string{"ALTER TABLE " + t + " DROP COLUMN " + col(c.Column)}, nil
	case AlterColumn:
		return g.alterColumn(t, *c.From, *c.Column), nil
	case AlterPrimaryKey:
		var out []string
		if len(c.FromPrimaryKey) > 0 {
			out = append(out, g.dropPrimaryKey(t))
		}
		if len(c.PrimaryKey) > 0 {
			out = append(out, "ALTER TABLE "+t+" ADD PRIMARY KEY ("+quoteList(d, c.PrimaryKey)+")")
		}
		return out, nil
	case AddIndex:
		if err := checkIndexColumns(*c.Index); err != nil {
			return nil, err
		}
		if c.Index.Constraint {
			return []string{"ALTER TABLE " + t + " ADD CONSTRAINT " + d.QuoteIdent(c.Index.Name) + " UNIQUE (" + quoteList(d, c.Index.Columns) + ")"}, nil
		}
		return []string{g.createIndex(c.Table)(*c.Index)}, nil
	case DropIndex:
		if c.Index.Constraint {
			return []string{"ALTER TABLE " + t + " DROP CONSTRAINT " + d.QuoteIdent(c.Index.Name)}, nil
		}
		return []string{"DROP INDEX " + qualifiedName(d, c.Table.Schema, c.Index.Name)}, nil
	}
	return nil, fmt.Errorf("unknown change %q", c.Kind)
}

func (g postgresDDL) createIndex(t dialect.Table) func(dialect.Index) string {
	return func(ix dialect.Index) string { return createIndexSQL(g.d, t, ix) }
}

// columnDef turns integer columns defaulting to a sequence into serial
// types, since the source's sequence does not exist on the target.
func (g postgresDDL) columnDef(c dialect.Column) string {
	typ, dflt := c.Type, c.Default
	if serial, ok := pgSerial[normalizeType(c.Type)]; ok && dflt != nil && pgNextval.MatchString(*dflt) {
		typ, dflt = serial, nil
	}
	s := g.d.QuoteIdent(c.Name) + " " + typ
	if c.AutoIncrement {
		s += " GENERATED BY DEFAULT AS IDENTITY"
	}
	s += nullClause(c)
	if dflt != nil {
		s += " DEFAULT " + *dflt
	}
	return s
}

func (g postgresDDL) alterColumn(t string, from, to dialect.Column) []string {
	alter := "ALTER TABLE " + t + " ALTER COLUMN " + g.d.QuoteIdent(to.Name) + " "
	var out []string
	if from.AutoIncrement && !to.AutoIncrement {
		out = append(out, alter+"DROP IDENTITY")
	}
	if typeChanged(from, to) {
		c := g.d.QuoteIdent(to.Name)
		out = append(out, alter+"TYPE "+to.Type+" USING "+c+"::"+to.Type)
	}
	if !defaultsEqual(from.Default, to.Default) {
		if to.Default == nil {
			out = append(out, alter+"DROP DEFAULT")
		} else {
			out = append(out, alter+"SET DEFAULT "+*to.Default)
		}
	}
	if from.Nullable != to.Nullable {
		if to.Nullable {
			out = append(out, alter+"DROP NOT NULL")
		} else {
			out = append(out, alter+"SET NOT NULL")
		}
	}
	if !from.AutoIncrement && to.AutoIncrement {
		out = append(out, alter+"ADD GENERATED BY DEFAULT AS IDENTITY")
	}
	return out
}

// dropPrimaryKey looks the constraint name up on the server; it is not part
// of the compared structure.
func (g postgresDDL) dropPrimaryKey(t string) string {
	lit := stringLiteral(t)
	return strings.Join([]string{
		"DO $synccraft$ DECLARE n name; BEGIN",
		"SELECT conname INTO n FROM pg_constraint WHERE conrelid = " + lit + "::regclass AND contype = 'p';",
		"IF n IS NOT NULL THEN EXECUTE format('ALTER TABLE %s DROP CONSTRAINT %I', " + lit + "::regclass, n); END IF;",
		"END $synccraft$",
	}, "\n")
}
